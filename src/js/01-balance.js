/* Настройки игрока. Хранятся в localStorage: игра — один файл без сервера.
   Обе по умолчанию выключены, то есть выключенное состояние — это привычная игра.

   bubbles — баблы с репликами. Реплики и так звучат голосом, а текст над толпой
   закрывает те самые кисти, по которым надо попадать. Плашки крика продавца это
   не касается: она одна и висит над прилавком, а не на людях.

   gentle — мягкий режим: та же игра без крови и отрубленных рук. Мачете
   заменяется свёрнутой газетой (широкая полоса вместо тонкого росчерка), нож —
   скомканным бумажным комом, культя — синяком на целой кисти. Правила, окна
   реакции и очки не меняются: это чисто визуальный слой, рекорды общие. */
const OPT = { bubbles:false, gentle:false };
const OPT_STORE = { bubbles:'ruki_opt_bubbles', gentle:'ruki_opt_gentle' };
const OPT_LABEL = { bubbles:'Реплики текстом', gentle:'Без крови' };
function loadOpts(){
  try{
    for(const k in OPT_STORE) OPT[k] = localStorage.getItem(OPT_STORE[k])==='1';
  }catch(e){}
}
function saveOpts(){
  try{
    for(const k in OPT_STORE) localStorage.setItem(OPT_STORE[k], OPT[k]?'1':'0');
  }catch(e){}
}

